def model_wait_summary(definition: dict[str, Any], turn: int, attempt: int) -> str:
    resumed = "Replacement Worker resumed the durable Activity. " if attempt > 1 else ""
    if definition.get("requires_model"):
        return (
            f"{resumed}Waiting for the local Ollama model to diagnose the evidence and generate "
            "the complete replacement source. The Worker is healthy; local inference can take several minutes."
        )
    return (
        f"{resumed}Waiting for the local Ollama model to choose the next bounded tool for reasoning turn {turn}. "
        "The Worker is healthy; local inference may take time."
    )


async def _run_with_heartbeat(function: Any, *args: Any, heartbeat: dict[str, Any]) -> Any:
    """Keep a blocking local model/tool call visible and quickly recoverable."""
    task = asyncio.create_task(asyncio.to_thread(function, *args))
    while not task.done():
        activity.heartbeat(heartbeat)
        try:
            return await asyncio.wait_for(asyncio.shield(task), timeout=0.75)
        except asyncio.TimeoutError:
            continue
    return await task


def execute_scoped_tool(tool: str, case_id: str, arguments: dict[str, Any]) -> dict[str, Any]:
    if tool == "code.patch":
        return apply_repair(case_id, arguments)
    if arguments:
        raise ValueError(f"Tool {tool} does not accept arguments")
    return TOOLS[tool](case_id)


@activity.defn(name="prepare_repair_case")
async def prepare_repair_case_activity(input: dict[str, Any]) -> dict[str, Any]:
    case_id = input["case_id"]
    strategy = input.get("side_effect_strategy", "none")
    lab = prepare_case(case_id, strategy)
    definitions = load_definitions()
    store = case_store()
    store.patch(case_id, {"status": "investigating", "lab": lab, "context": {"event": lab["event"], "original_failure": lab["failure"], "repo": lab["repo"], "side_effect_strategy": strategy}})
    store.timeline(case_id, "event", "Runtime failure captured", "Order Service failed against Inventory contract v2.", lab["event"])
    store.timeline(case_id, "temporal", "Temporal case started", "Parent Workflow scheduled two investigation child Workflows in parallel.")
    return {"lab": lab, "definitions": definitions}


@activity.defn(name="agent_model_turn")
async def agent_model_turn_activity(input: dict[str, Any]) -> dict[str, Any]:
    store = case_store()
    agent_id = input["agent_id"]
    attempt = activity.info().attempt
    summary = model_wait_summary(input["definition"], input["turn"], attempt)
    store.agent(
        input["case_id"], agent_id, status="reasoning", turn=input["turn"],
        active_tool=None, last_summary=summary,
    )
    store.timeline(
        input["case_id"], "model",
        f"{input['definition']['name']} waiting for Ollama · turn {input['turn']} · attempt {attempt}",
        summary, {"agent_id": agent_id, "turn": input["turn"], "activity_attempt": attempt},
        status="running", event_id=f"model-start-{agent_id}-{input['turn']}-{attempt}",
    )
    await asyncio.sleep(float(input.get("step_delay", 0.25)))
    command = await _run_with_heartbeat(
        model_turn, input["definition"], input["context"], input["observations"],
        heartbeat={"phase": "model_turn", "agent_id": agent_id, "turn": input["turn"], "attempt": attempt},
    )
    store.agent(input["case_id"], agent_id, status="reasoning", turn=input["turn"], model_mode=command.get("model_mode"), last_summary=command.get("summary", ""))
    store.timeline(input["case_id"], "model", f"{input['definition']['name']} reasoning turn {input['turn']}", command.get("summary", "Structured command returned."), command)
    return command


@activity.defn(name="agent_tool")
async def agent_tool_activity(input: dict[str, Any]) -> dict[str, Any]:
    tool = input["tool"]
    if tool not in input["definition"]["tools"] or tool not in TOOLS:
        raise ValueError(f"Tool {tool} is not allowed for {input['agent_id']}")
    store = case_store()
    attempt = activity.info().attempt
    resumed = "Replacement Worker resumed this durable tool call. " if attempt > 1 else ""
    summary = resumed + TOOL_WAIT_SUMMARIES.get(tool, f"Running the scoped local tool {tool}.")
    store.agent(
        input["case_id"], input["agent_id"], status="using_tool",
        active_tool=tool, last_summary=summary,
    )
    store.timeline(
        input["case_id"], "tool", f"{input['definition']['name']} called {tool} · attempt {attempt}",
        summary, {"arguments": input.get("arguments", {}), "activity_attempt": attempt},
        status="running", event_id=f"tool-start-{input['agent_id']}-{tool}-{attempt}",
    )
    try:
        result = await _run_with_heartbeat(
            execute_scoped_tool, tool, input["case_id"], input.get("arguments", {}),
            heartbeat={"phase": "tool", "agent_id": input["agent_id"], "tool": tool, "attempt": attempt},
        )
    except (SyntaxError, ValueError) as error:
        if tool != "code.patch":
            raise
        result = {
            "success": False,
            "error_type": type(error).__name__,
            "error": str(error),
            "message": "The guarded patch validator rejected the model-authored source; the error is returned to Ollama for another repair turn.",
        }
    observation = {"tool": tool, "arguments": input.get("arguments", {}), "result": result}
    current = store.get(input["case_id"]) or {}
    agent = current.get("agents", {}).get(input["agent_id"], {})
    observations = [*agent.get("observations", []), observation]
    store.agent(input["case_id"], input["agent_id"], status="reasoning", active_tool=None, observations=observations)
    store.timeline(input["case_id"], "tool_result", f"{tool} returned evidence", "Result recorded in Temporal history and the SignalRoom projection.", result)
    return observation


