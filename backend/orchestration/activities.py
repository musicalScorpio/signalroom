def _side_effect_agent(store: Any, case_id: str, **changes: Any) -> None:
    store.agent(case_id, "side_effect", **changes)


@activity.defn(name="execute_case_external_effect")
async def execute_case_external_effect_activity(input: dict[str, Any]) -> dict[str, Any]:
    """Run model-authored branch code and expose the provider/result ambiguity window."""
    store = case_store()
    case_id = input["case_id"]
    attempt = activity.info().attempt
    strategy = input["side_effect_strategy"]
    tool = "payments.create_idempotent" if strategy == "native_idempotency" else "payments.create_once"
    request = {
        "agent": "Side-Effect Execution Agent",
        "tool": tool,
        "method": "POST",
        "route": "/payments/idempotent" if strategy == "native_idempotency" else "/payments/non-idempotent",
        "headers": {"Idempotency-Key": input["operation_id"]} if strategy == "native_idempotency" else {},
        "body": {"payment_code": input["payment_code"], "amount_cents": input["amount_cents"]},
        "activity_attempt": attempt,
        "maximum_attempts": 4 if strategy == "native_idempotency" else 1,
        "source": "model-authored order_service.checkout",
    }
    if attempt > 1:
        store.timeline(
            case_id, "worker", "Replacement Worker resumed the external-effect Activity",
            f"Worker PID {os.getpid()} received Activity attempt {attempt} with the same operation identity and repaired-branch assignment.",
            {"replacement_worker_pid": os.getpid(), "activity_attempt": attempt, "request": request},
            status="recovered", event_id=f"external-worker-resumed-{case_id}-{attempt}",
        )
        store.timeline(
            case_id, "temporal", "Temporal replayed the unresolved side-effect assignment",
            "The provider receipt was absent from Event History, so Temporal applied the recorded retry policy rather than restarting the case.",
            {"strategy": strategy, "operation_id": input["operation_id"], "activity_attempt": attempt},
            status="recovered", event_id=f"external-temporal-replay-{case_id}-{attempt}",
        )
    store.patch(case_id, {"status": "calling_external_api"})
    _side_effect_agent(
        store, case_id, status="using_tool", turn=attempt, active_tool=tool,
        last_summary=f"Attempt {attempt}: executing the reviewed branch and calling the local provider under {strategy}.",
    )
    store.timeline(
        case_id, "agent", f"Side-Effect Execution Agent called {tool} · attempt {attempt}",
        "The call originates in the exact model-authored order_service.py that passed review tests.",
        request, status="running", event_id=f"external-call-{case_id}-{attempt}",
    )
    result = await _run_with_heartbeat(
        execute_checkout_with_provider,
        case_id, strategy, input["operation_id"], input["payment_code"], int(input["amount_cents"]),
        heartbeat={"phase": "calling_provider", "attempt": attempt, "operation_id": input["operation_id"]},
    )
    provider_result = result["provider_result"]
    payment = provider_result.get("payment", {})
    replayed = bool(provider_result.get("replayed"))
    observation = {"id": f"external-result-{attempt}", "tool": tool, "request": request, "result": result}

    def record_effect(case: dict[str, Any]) -> None:
        side_effect = case.setdefault("side_effect", {})
        side_effect.update({
            "status": "provider_replayed" if replayed else "provider_committed",
            "danger_window": not replayed,
            "activity_attempt": attempt,
            "provider_result": provider_result,
            "external_payment_id": payment.get("id"),
        })
        agent = case.setdefault("agents", {}).setdefault("side_effect", {})
        observations = agent.setdefault("observations", [])
        if not any(item.get("id") == observation["id"] for item in observations):
            observations.append(observation)
    store.mutate(case_id, record_effect)
    store.timeline(
        case_id, "provider",
        "Provider replayed the original receipt" if replayed else "Provider committed the external payment",
        ("The repeated POST reused the stable Idempotency-Key; no second payment row was created."
         if replayed else "The provider database now contains the effect, but Temporal has not recorded this Activity result yet."),
        {"request": request, "provider_response": provider_result, "result_gap": not replayed},
        status="recovered" if replayed else "danger", event_id=f"external-provider-{case_id}-{attempt}",
    )
    if replayed:
        _side_effect_agent(store, case_id, status="completed", active_tool=None, last_summary="Provider replayed the first receipt; duplicate creation was prevented.")
        return result

    auto_crash = bool(input.get("auto_crash"))
    current = store.get(case_id) or {}
    crash_state = current.get("side_effect", {}).get("auto_crash_state")
    if auto_crash and crash_state == "armed":
        def consume_crash(case: dict[str, Any]) -> None:
            case.setdefault("side_effect", {}).update({"auto_crash_state": "consumed", "danger_window": True})
            agent = case.setdefault("agents", {}).setdefault("side_effect", {})
            agent.update({
                "status": "interrupted", "active_tool": None,
                "last_summary": "Worker was deliberately killed after provider commit and before Temporal recorded the receipt.",
            })
        store.mutate(case_id, consume_crash)
        store.timeline(
            case_id, "worker", "Agent Worker killed automatically in the result gap",
            f"Worker PID {os.getpid()} was terminated after the provider commit. The Side-Effect Execution Agent lost in-memory state.",
            {"worker_pid": os.getpid(), "interrupted_agent": "side_effect", "interrupted_agents": [{"agent_id": "side_effect", "name": "Side-Effect Execution Agent", "status": "waiting_for_receipt", "turn": attempt, "active_tool": tool}], "activity_attempt": attempt, "provider_payment": payment, "automatic": True},
            status="interrupted", event_id=f"external-auto-kill-{case_id}",
        )
        store.timeline(
            case_id, "temporal", "Temporal retained the unresolved external-effect Activity",
            "Workflow history still contains the reviewed commit, strategy, operation ID, and retry rule, but not the missing provider receipt.",
            {"strategy": strategy, "operation_id": input["operation_id"], "reviewed_commit": input.get("reviewed_commit")},
            status="durable", event_id=f"external-auto-retained-{case_id}",
        )
        activity.heartbeat({"phase": "provider_committed_before_auto_crash", "payment_id": payment.get("id"), "attempt": attempt})
        os.kill(os.getpid(), signal.SIGKILL)

    hold_seconds = max(0.0, float(input.get("hold_seconds", 20.0)))
    elapsed = 0.0
    _side_effect_agent(store, case_id, status="waiting_for_receipt", active_tool=tool, last_summary="Provider committed; waiting in the manual result-gap crash window.")
    while elapsed < hold_seconds:
        activity.heartbeat({"phase": "provider_committed", "payment_id": payment.get("id"), "attempt": attempt})
        interval = min(0.5, hold_seconds - elapsed)
        await asyncio.sleep(interval)
        elapsed += interval
    _side_effect_agent(store, case_id, status="completed", active_tool=None, last_summary="Provider receipt reached Temporal without a Worker failure.")
    return result


@activity.defn(name="lookup_case_external_effect")
async def lookup_case_external_effect_activity(input: dict[str, Any]) -> dict[str, Any]:
    store = case_store()
    case_id = input["case_id"]
    check = int(input.get("check", 0))
    result = await asyncio.to_thread(find_payments, input["payment_code"], True)
    request = {
        "agent": "Side-Effect Execution Agent", "tool": "payments.lookup", "method": "GET",
        "route": f"/payments?payment_code={input['payment_code']}", "check": check,
        "result_count": result.get("count", 0), "safe_to_retry": True,
    }
    _side_effect_agent(
        store, case_id, status="using_tool", turn=check + 1, active_tool="payments.lookup",
        last_summary="Suppressing a second POST and reconciling provider truth with a repeatable GET.",
    )
    store.timeline(
        case_id, "agent", "Side-Effect Execution Agent used safe GET reconciliation",
        "The non-idempotent POST remains suppressed. This read can be repeated without creating another payment.",
        {"request": request, "provider_response": result}, event_id=f"external-lookup-{case_id}-{check}",
    )
    return result


@activity.defn(name="record_case_external_stage")
async def record_case_external_stage_activity(input: dict[str, Any]) -> dict[str, Any]:
    store = case_store()
    case_id = input["case_id"]
    changes = input.get("changes", {})
    def update(case: dict[str, Any]) -> None:
        case["status"] = input["status"]
        side_effect = case.setdefault("side_effect", {})
        side_effect.update({"status": input.get("side_effect_status", input["status"]), "danger_window": False, **changes})
        agent = case.setdefault("agents", {}).setdefault("side_effect", {})
        terminal = input.get("agent_status")
        if terminal:
            agent.update({"status": terminal, "active_tool": None, "last_summary": input.get("agent_summary", input["detail"])})
    record = store.mutate(case_id, update)
    store.timeline(
        case_id, input.get("kind", "temporal"), input["title"], input["detail"],
        input.get("data", changes), status=input.get("timeline_status", "complete"), event_id=input.get("event_id"),
    )
    return record or {}
